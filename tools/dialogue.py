def sentences(words):
    """A sentence boundary inside a quoted example still belongs to the teller."""
    words = words.strip()
    if words.startswith('“') and words.endswith('”'):
        words = words[1:-1]
    words = words.replace('“','「').replace('”','」')
    pending, depth = '', 0
    for char in words:
        pending += char
        if char in '「『':
            depth += 1
        elif char in '」』':
            depth = max(0, depth-1)
        if depth == 0 and (char in '。！？' or (char in '」』' and re.search(r'[。！？][」』]+$', pending))):
            yield pending.strip()
            pending = ''
    if pending.strip():
        yield pending.strip()

def annotate(key, paragraphs):
    result = []
    for index, para in enumerate(paragraphs):
        source_id = f'{key}:p{index}'
        patch = PATCHES.get((key,index))
        if patch:
            prefix, segments = patch
            assert para['text'].startswith(prefix), (key,index,prefix,para['text'])
        else:
            match = re.fullmatch(r'(我|他|她)(?:说|问|口述)：(.+)', para['text'], re.S)
            if match:
                speaker = '我' if match[1]=='我' else SPEAKERS[key]
                segments = [(speaker,match[2])]
            else:
                segments = [para['text']]
        start = len(result)
        for part, segment in enumerate(segments):
            base = {'when':para['when'], 'sourceId':source_id, 'segment':part}
            if isinstance(segment,str):
                if segment.strip():
                    result.append({**base,'kind':'prose','text':segment})
            else:
                speaker, words = segment
                for sentence, words in enumerate(sentences(words)):
                    result.append({**base,'kind':'dialogue','speaker':speaker,'text':words,'sentence':sentence})
        result[start]['sourceText'] = para['text']
    return result
